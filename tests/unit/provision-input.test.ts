import { randomBytes } from "node:crypto";
import { beforeEach, afterEach, expect, it, vi } from "vitest";
const state = vi.hoisted(() => ({ answers: [] as string[], output: null as null | { write(value: string): void }, close: vi.fn(), append: vi.fn(), read: vi.fn() }));
vi.mock("node:readline/promises", () => ({ createInterface: (options: { output: typeof state.output }) => {
  state.output = options.output;
  return { question: async () => {
    const answer = state.answers.shift() ?? "";
    state.output?.write(answer); // Simulate the terminal echo generated by readline.
    return answer;
  }, close: state.close };
} }));
vi.mock("node:fs/promises", () => ({ appendFile: state.append, readFile: state.read }));
import { promptProvisioning } from "../../scripts/provision-input";
const adminSecret = randomBytes(24).toString("base64url");
const operationsSecret = randomBytes(24).toString("base64url");
const descriptors = [Object.getOwnPropertyDescriptor(process.stdin, "isTTY"), Object.getOwnPropertyDescriptor(process.stdout, "isTTY")];
beforeEach(() => {
  Object.defineProperty(process.stdin, "isTTY", { value: true, configurable: true });
  Object.defineProperty(process.stdout, "isTTY", { value: true, configurable: true });
  state.answers = []; state.close.mockClear(); state.append.mockReset(); state.read.mockReset();
  state.read.mockResolvedValue("DATABASE_URL=existing\n");
});
afterEach(() => {
  for (const [index, stream] of [process.stdin, process.stdout].entries()) {
    if (descriptors[index]) Object.defineProperty(stream, "isTTY", descriptors[index]!);
    else Reflect.deleteProperty(stream, "isTTY");
  }
  vi.restoreAllMocks();
});
it("hides password entry and confirmation, persists only public origin, and returns details in memory", async () => {
  state.answers = ["http://localhost:3000", "admin@example.test", "", adminSecret, adminSecret, "ops@example.test", "", operationsSecret, operationsSecret];
  const write = vi.spyOn(process.stdout, "write").mockImplementation(() => true);
  const input = await promptProvisioning({});
  expect(input.AUTH_ADMIN_PASSWORD).toBe(adminSecret);
  expect(input.AUTH_OPERATIONS_PASSWORD).toBe(operationsSecret);
  expect(input.AUTH_ADMIN_NAME).toBe("Admin");
  const visible = write.mock.calls.map(([chunk]) => String(chunk)).join("");
  expect(visible).not.toContain(adminSecret);
  expect(visible).not.toContain(operationsSecret);
  expect(state.append).toHaveBeenCalledExactlyOnceWith(".env", '\nAUTH_ORIGIN="http://localhost:3000"\n', { mode: 0o600 });
  expect(state.close).toHaveBeenCalledOnce();
});
it("rejects mismatched confirmations before writing local configuration", async () => {
  state.answers = ["http://localhost:3000", "admin@example.test", "", adminSecret, operationsSecret];
  vi.spyOn(process.stdout, "write").mockImplementation(() => true);
  await expect(promptProvisioning({})).rejects.toThrow("confirmation");
  expect(state.append).not.toHaveBeenCalled();
  expect(state.close).toHaveBeenCalledOnce();
});
it("requires an actual terminal for hidden input", async () => {
  Object.defineProperty(process.stdin, "isTTY", { value: false, configurable: true });
  await expect(promptProvisioning({})).rejects.toThrow("local terminal");
  expect(state.append).not.toHaveBeenCalled();
});
